export const QIcono = ({
  nombre,
  tamaño = "md",
  color,
  relleno,
  style,
}: QIconoProps) => {
  const Icono = iconos[nombre] ?? IconQuestionMark;
  const size = tamaños[tamaño] ?? 20;
  const fill =
    typeof relleno === "string"
      ? relleno
      : relleno
        ? "var(--color-primario-claro)"
        : undefined;

  return (
    <quimera-icono>
      <Icono
        size={size}
        color={color}
        style={style}
        {...(fill ? { fill } : {})}
      />
    </quimera-icono>
  );
};
